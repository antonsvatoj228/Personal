KM = "'Керування прайсом'"
DK = "'Довідник категорій'"

def col_letter(i):
    s = ""
    while i > 0:
        i, r = divmod(i - 1, 26)
        s = chr(65 + r) + s
    return s

LASTL = col_letter(LAST_COL)

